CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,  -- автоинкрементный первичный ключ
    name VARCHAR(255) NOT NULL,                            -- имя пользователя
    email VARCHAR(512) NOT NULL,                           -- email (должен быть уникальным)
    CONSTRAINT pk_user PRIMARY KEY (id),                   -- первичный ключ
    CONSTRAINT UQ_USER_EMAIL UNIQUE (email)                -- запрет дубликатов email на уровне БД
    );

CREATE TABLE IF NOT EXISTS requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    description VARCHAR(2000) NOT NULL,
    requestor_id BIGINT NOT NULL,
    created TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_request PRIMARY KEY (id),
    CONSTRAINT fk_requests_requestor FOREIGN KEY (requestor_id) REFERENCES users (id)
    );

CREATE TABLE IF NOT EXISTS items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(255) NOT NULL,                            -- название вещи
    description VARCHAR(2000) NOT NULL,                    -- описание вещи
    is_available BOOLEAN NOT NULL,                         -- доступна ли вещь для аренды
    owner_id BIGINT NOT NULL,                              -- владелец (ссылка на users.id)
    request_id BIGINT,                                     -- ссылка на requests.id (может быть NULL)
    CONSTRAINT pk_item PRIMARY KEY (id),
    CONSTRAINT fk_items_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT fk_items_request FOREIGN KEY (request_id) REFERENCES requests (id)
    );

CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    start_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,       -- начало бронирования
    end_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,         -- конец бронирования
    item_id BIGINT NOT NULL,                               -- какая вещь бронируется
    booker_id BIGINT NOT NULL,                             -- кто бронирует
    status VARCHAR(16) NOT NULL,                           -- статус (WAITING/APPROVED/REJECTED/CANCELED)
    CONSTRAINT pk_booking PRIMARY KEY (id),
    CONSTRAINT fk_bookings_item FOREIGN KEY (item_id) REFERENCES items (id),
    CONSTRAINT fk_bookings_booker FOREIGN KEY (booker_id) REFERENCES users (id)
    );

CREATE TABLE IF NOT EXISTS comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    text VARCHAR(4000) NOT NULL,                           -- текст отзыва
    item_id BIGINT NOT NULL,                               -- о какой вещи отзыв
    author_id BIGINT NOT NULL,                             -- кто написал отзыв
    created TIMESTAMP WITHOUT TIME ZONE NOT NULL,          -- дата создания отзыва
    CONSTRAINT pk_comment PRIMARY KEY (id),
    CONSTRAINT fk_comments_item FOREIGN KEY (item_id) REFERENCES items (id),
    CONSTRAINT fk_comments_author FOREIGN KEY (author_id) REFERENCES users (id)
    );